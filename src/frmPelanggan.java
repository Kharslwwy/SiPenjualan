    private void txtKodeFocusLost(java.awt.event.FocusEvent evt) {//GEN-FIRST:event_txtKodeFocusLost
        // TODO add your handling code here:
        clsPelanggan plg = new clsPelanggan();

        plg.setKode(txtKode.getText());
        plg.tampil();

        if (plg.getFlag() == 4)
        {
            txtNama.setText(plg.getNama());
            txtAlamat.setText(plg.getAlamat());
            txtTelepon.setText(plg.getTelepon());
            txtNama.requestFocus();
            btnSimpan.setEnabled(false);
            btnUbah.setEnabled(true);
            btnHapus.setEnabled(true);
        }
        else
        {
            txtNama.setText("");
            txtAlamat.setText("");
            txtTelepon.setText("");
            txtNama.requestFocus();
            btnSimpan.setEnabled(true);
            btnUbah.setEnabled(false);
            btnHapus.setEnabled(false);
        }
    }//GEN-LAST:event_txtKodeFocusLost

    private void TableviewDataMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_TableviewDataMouseClicked
        // TODO add your handling code here:
        int tabelData = TableviewData.getSelectedRow();

        txtKode.setText("" + TableviewData.getValueAt(tabelData, 0));
        txtNama.setText("" + TableviewData.getValueAt(tabelData, 1));
        txtAlamat.setText("" + TableviewData.getValueAt(tabelData, 2));
        txtTelepon.setText("" + TableviewData.getValueAt(tabelData, 3));
        txtNama.requestFocus();
        btnSimpan.setEnabled(false);
        btnUbah.setEnabled(true);
        btnHapus.setEnabled(true);
    }//GEN-LAST:event_TableviewDataMouseClicked

    private void txtKodeKeyPressed(java.awt.event.KeyEvent evt) {//GEN-FIRST:event_txtKodeKeyPressed
        // TODO add your handling code here:
        if (evt.getKeyCode() == KeyEvent.VK_ENTER) {
            clsPelanggan plg = new clsPelanggan();

            plg.setKode(txtKode.getText().trim()); 
            plg.tampil(); 

            if (plg.getFlag() == 4) {
                // jika data ditemukan
                txtNama.setText(plg.getNama());
                txtAlamat.setText(plg.getAlamat());
                txtTelepon.setText(plg.getTelepon());
                txtNama.requestFocus();
                btnSimpan.setEnabled(false);
                btnUbah.setEnabled(true);
                btnHapus.setEnabled(true);
            } else {
                // jika tidak ditemukan
                JOptionPane.showMessageDialog(this, "Data tidak ditemukan!");
                txtNama.setText("");
                txtAlamat.setText("");
                txtTelepon.setText("");
                txtNama.requestFocus();
                btnSimpan.setEnabled(true);
                btnUbah.setEnabled(false);
                btnHapus.setEnabled(false);
        }
    }
        
    }//GEN-LAST:event_txtKodeKeyPressed


