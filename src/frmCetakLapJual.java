    private void btnCetakActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCetakActionPerformed
        try {    
            Koneksi k = new Koneksi();
            Connection cn = k.openKoneksi();

            String nmFile = Paths.get("C:", "Users", "LENOVO", "OneDrive", 
                          "JaspersoftWorkspace", "nota", "lapjual.jasper").toString();

            // Ambil tanggal awal
            java.util.Date utilDate1 = txtPeriode1.getDate();
            if (utilDate1 == null) {
                JOptionPane.showMessageDialog(this, "Tanggal awal belum dipilih!", "Error", JOptionPane.ERROR_MESSAGE);
                return;
            }
            java.sql.Date sqlDate1 = new java.sql.Date(utilDate1.getTime());

            // Ambil tanggal akhir
            java.util.Date utilDate2 = txtPeriode2.getDate();
            if (utilDate2 == null) {
                JOptionPane.showMessageDialog(this, "Tanggal akhir belum dipilih!", "Error", JOptionPane.ERROR_MESSAGE);
                return;
            }
            java.sql.Date sqlDate2 = new java.sql.Date(utilDate2.getTime());

            // Kirim parameter ke laporan Jasper
            HashMap<String, Object> map = new HashMap<>();
            map.put("periode1", sqlDate1);
            map.put("periode2", sqlDate2);

            File reportFile = new File(nmFile);
            JasperReport jReport = (JasperReport) JRLoader.loadObject(reportFile.getPath());
            JasperPrint jPrint = JasperFillManager.fillReport(jReport, map, cn);
            JasperViewer.viewReport(jPrint, false);
            JasperViewer.setDefaultLookAndFeelDecorated(true);

        } catch (Exception sqe) {
            JOptionPane.showMessageDialog(null, "Laporan tidak dapat dicetak: " +
                sqe.getMessage(), "Cetak Laporan",
                JOptionPane.ERROR_MESSAGE);
        }

        // TODO add your handling code here:
    }//GEN-LAST:event_btnCetakActionPerformed

