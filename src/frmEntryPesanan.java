    private void btnSimpanActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSimpanActionPerformed
       clsPesanan psn = new clsPesanan();
            psn.setNoPesan(txtNoPsn.getText());
             java.util.Date utilDate = txtTglPsn.getDate();
             if (utilDate != null) {
                 java.sql.Date sqlDate = new java.sql.Date(utilDate.getTime());
                 psn.setTanggal(sqlDate);
             } else {
                 JOptionPane.showMessageDialog(this, "Tanggal belum dipilih!", "Error", JOptionPane.ERROR_MESSAGE);
                 return;
             }
            psn.setKodePelanggan("" + cmbKdPlg.getSelectedItem());

            // 1. Simpan pesanan dulu
            psn.simpanPesanan();

            int baris = tabMode.getRowCount();
            for (int i = 0; i < baris; i++) {
                psn.setKodeBarang("" + viewDataPesan.getValueAt(i, 0));
                psn.setHarga(Integer.parseInt("" + viewDataPesan.getValueAt(i, 2)));
                psn.setJumlah(Integer.parseInt("" + viewDataPesan.getValueAt(i, 3)));

                // 2. Simpan detail pesanan
                psn.simpanDetailPesan();

                // 3. Update stok barang
                psn.updateStok();
            }

            kosong();
            comboBarang();
            comboPelanggan();

    }//GEN-LAST:event_btnSimpanActionPerformed

