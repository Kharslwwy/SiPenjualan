    private void cmbKdPlgActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_cmbKdPlgActionPerformed

        if (cmbKdPlg.getSelectedIndex() <= 0) {
            // Jika masih pilih item dummy, kosongkan field
            txtNmPlg.setText("");
            txtAlmPlg.setText("");
            txtTlpPlg.setText("");
            return;
        }

        clsPelanggan plg = new clsPelanggan();
        plg.setKode(""+cmbKdPlg.getSelectedItem());
        plg.tampil();
        txtNmPlg.setText(plg.getNama());
        txtAlmPlg.setText(plg.getAlamat());
        txtTlpPlg.setText(plg.getTelepon());
        cmbKdBrg.requestFocus();
        
    }//GEN-LAST:event_cmbKdPlgActionPerformed

