    public void kosong()
    {
        clsNota nt = new clsNota();
        
        txtNoNota.setText("");
        txtTglNota.setDate(null);
        cmbNoPesan.removeAllItems();
        btnCetak.setEnabled(false);
        nt.autoNoNota();
        txtNoNota.setText(nt.getNoNota());
    }
    
    public void comboPesanan()
    {
        try
        {
            cmbNoPesan.removeAllItems(); 
            cmbNoPesan.addItem("-- Pilih Pesanan --"); // item dummy
            
            Koneksi k = new Koneksi();
            Connection cn = k.openKoneksi();
            Statement st = cn.createStatement();
            String sql = "SELECT nopesan FROM pesanan ";
                   sql+= "WHERE nopesan NOT IN (";
                   sql+= "SELECT nopesan from nota)";
            ResultSet rs = st.executeQuery(sql);
            
            while(rs.next())
            {
            cmbNoPesan.addItem(rs.getString("nopesan"));
            }
            st.close();
            cn.close();
        }
        catch(SQLException sqe)
        {}
            
    }
    
